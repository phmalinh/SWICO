function resolveLocale(value) {
  return value === 'zh-Hant' ? 'zh-Hant' : 'vi'
}

export function createI18n() {
  const locale = ref(resolveLocale(localStorage.getItem('swico_locale')))

  const setLocale = value => {
    const normalized = resolveLocale(value)
    locale.value = normalized
    localStorage.setItem('swico_locale', normalized)
  }

  const t = (key, params = {}) => {
    const parts = key.split('.')
    let current = messages[locale.value]
    for (const part of parts) {
      if (!current || typeof current !== 'object' || !(part in current)) {
        return key
      }
      current = current[part]
    }
    if (typeof current !== 'string') return key
    return Object.entries(params).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), current)
  }

  return {
    install(app) {
      app.provide('i18n', { locale, messages, t, setLocale })
      app.config.globalProperties.$t = t
      app.config.globalProperties.$locale = locale
      app.config.globalProperties.$setLocale = setLocale
    },
    locale,
    messages,
    t,
    setLocale,
  }
}

export function useI18n() {
  const context = inject('i18n')
  if (!context) {
    throw new Error('useI18n must be used within an i18n provider')
  }
  return context
}
